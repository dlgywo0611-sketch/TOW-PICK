'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = { globalThis: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '..', 'frontend', 'session-scope-logic.js'), 'utf8'), context);
const logic = context.globalThis.TwoPickSessionScopeLogic;
const scope = logic.createSessionScope();
const firstRequest = scope.snapshot();
assert.equal(scope.isCurrent(firstRequest), true);
scope.invalidate();
assert.equal(scope.isCurrent(firstRequest), false);
const secondRequest = scope.snapshot();
assert.equal(scope.isCurrent(secondRequest), true);
assert.equal(logic.staleSessionError().staleSession, true);
const settingsSource = fs.readFileSync(path.join(__dirname, '..', 'frontend', 'settings.js'), 'utf8');
assert.match(settingsSource, /tow_pick_local_nickname_\$\{userId\}/);
console.log('PASS: account switches invalidate old requests and profile names are user-scoped');
