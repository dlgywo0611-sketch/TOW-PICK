'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = { globalThis: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '..', 'frontend', 'schedule-api-logic.js'), 'utf8'), context);
const logic = context.globalThis.TwoPickScheduleApiLogic;
const valid = logic.validateInput({ title: ' 기념일 ', kind: 'anniversary', local_date: '2026-11-25', local_time: '', repeat_rule: 'yearly' });
assert.equal(valid.valid, true); assert.equal(valid.value.local_time, null);
assert.equal(logic.validateInput({ title: 'x', kind: 'anniversary', local_date: '2026-11-25', repeat_rule: 'weekly' }).valid, false);
assert.equal(logic.occurrencesForMonth({ local_date: '2026-11-03', repeat_rule: 'weekly', kind: 'schedule' }, 2026, 10).length, 4);
assert.equal(logic.occurrencesForMonth({ local_date: '2025-11-25', repeat_rule: 'yearly', kind: 'anniversary' }, 2026, 10)[0].date, '2026-11-25');
assert.equal(logic.occurrencesForMonth({ local_date: '2026-01-31', repeat_rule: 'monthly', kind: 'schedule' }, 2026, 1)[0].date, '2026-02-28');
assert.equal(logic.occurrencesForMonth({ local_date: '2024-02-29', repeat_rule: 'yearly', kind: 'anniversary' }, 2025, 1)[0].date, '2025-02-28');
assert.equal(logic.occurrencesForMonth({ local_date: '2024-02-29', repeat_rule: 'yearly', kind: 'anniversary' }, 2028, 1)[0].date, '2028-02-29');
assert.equal(logic.seoulDateParts(new Date('2026-11-25T15:30:00Z')).key, '2026-11-26');
assert.equal(logic.upcomingOccurrences([{ id: 1, local_date: '2025-11-25', repeat_rule: 'yearly', kind: 'anniversary' }], new Date('2026-11-23T15:00:00Z'), 3)[0].date, '2026-11-25');
assert.equal(logic.buildCalendarDays(2026, 10, []).length, 42);
console.log('PASS: schedule recurrence matches backend clamping and uses Asia/Seoul dates');
